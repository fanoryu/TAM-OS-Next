CREATE TABLE finance_request_payments (
  id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  company_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  finance_request_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  finance_transaction_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  paid_on DATE NOT NULL,
  payment_method VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  amount DECIMAL(17,2) NOT NULL,
  paid_by_user_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  idempotency_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(6) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY finance_request_payments_company_id (company_id, id),
  UNIQUE KEY finance_request_payments_request (finance_request_id),
  UNIQUE KEY finance_request_payments_transaction (finance_transaction_id),
  UNIQUE KEY finance_request_payments_idempotency_key (company_id, idempotency_key),
  KEY finance_request_payments_company_request (company_id, finance_request_id),
  KEY finance_request_payments_company_transaction (company_id, finance_transaction_id),
  CONSTRAINT finance_request_payments_company_fk FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT finance_request_payments_request_fk FOREIGN KEY (company_id, finance_request_id) REFERENCES finance_requests (company_id, id),
  CONSTRAINT finance_request_payments_transaction_fk FOREIGN KEY (company_id, finance_transaction_id) REFERENCES finance_transactions (company_id, id),
  CONSTRAINT finance_request_payments_paid_by_fk FOREIGN KEY (paid_by_user_id) REFERENCES users (id),
  CONSTRAINT finance_request_payments_id CHECK (id REGEXP '^[0-9a-f]{32}$'),
  CONSTRAINT finance_request_payments_paid_on CHECK (paid_on >= '1900-01-01'),
  CONSTRAINT finance_request_payments_method CHECK (payment_method IN ('cash', 'bankTransfer', 'qris', 'virtualAccount', 'creditCard', 'other')),
  CONSTRAINT finance_request_payments_amount CHECK (amount > 0 AND amount = FLOOR(amount)),
  CONSTRAINT finance_request_payments_paid_by CHECK (paid_by_user_id REGEXP '^[0-9a-f]{32}$'),
  CONSTRAINT finance_request_payments_idempotency_key_format CHECK (idempotency_key REGEXP '^[0-9a-f]{32}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
