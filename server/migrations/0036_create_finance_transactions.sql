CREATE TABLE finance_transactions (
  id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  company_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  kind VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  financial_post VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  category VARCHAR(64) NOT NULL,
  description VARCHAR(500) NOT NULL,
  amount DECIMAL(17,2) NOT NULL,
  transaction_date DATE NOT NULL,
  created_by_user_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  idempotency_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(6) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY finance_transactions_company_id (company_id, id),
  UNIQUE KEY finance_transactions_idempotency_key (company_id, idempotency_key),
  KEY finance_transactions_date (company_id, transaction_date, id),
  KEY finance_transactions_post_date (company_id, financial_post, transaction_date),
  CONSTRAINT finance_transactions_company_fk FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT finance_transactions_created_by_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id),
  CONSTRAINT finance_transactions_id CHECK (id REGEXP '^[0-9a-f]{32}$'),
  CONSTRAINT finance_transactions_kind CHECK (kind IN ('income', 'expense')),
  CONSTRAINT finance_transactions_financial_post CHECK (financial_post IN ('GA', 'NPIP', 'TJB', 'DRONE')),
  CONSTRAINT finance_transactions_category CHECK (CHAR_LENGTH(category) BETWEEN 1 AND 64 AND CHAR_LENGTH(category) = CHAR_LENGTH(TRIM(category)) AND LOWER(category) NOT IN ('gaji', 'payroll', 'salary')),
  CONSTRAINT finance_transactions_description CHECK (CHAR_LENGTH(description) BETWEEN 1 AND 500 AND CHAR_LENGTH(description) = CHAR_LENGTH(TRIM(description))),
  CONSTRAINT finance_transactions_amount CHECK (amount > 0 AND amount = FLOOR(amount)),
  CONSTRAINT finance_transactions_date_range CHECK (transaction_date >= '1900-01-01'),
  CONSTRAINT finance_transactions_created_by CHECK (created_by_user_id REGEXP '^[0-9a-f]{32}$'),
  CONSTRAINT finance_transactions_idempotency_key_format CHECK (idempotency_key REGEXP '^[0-9a-f]{32}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
