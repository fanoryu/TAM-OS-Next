CREATE TABLE finance_requests (
  id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  company_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  kind VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  financial_post VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  category VARCHAR(64) NOT NULL,
  description VARCHAR(500) NOT NULL,
  amount DECIMAL(17,2) NOT NULL,
  payee VARCHAR(160) NULL,
  owner_employee_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  document_date DATE NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status_reason VARCHAR(200) NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  idempotency_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_by_user_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY finance_requests_company_id (company_id, id),
  UNIQUE KEY finance_requests_idempotency_key (company_id, idempotency_key),
  KEY finance_requests_status_date (company_id, status, document_date),
  KEY finance_requests_owner (company_id, owner_employee_id),
  CONSTRAINT finance_requests_company_fk FOREIGN KEY (company_id) REFERENCES companies (id),
  CONSTRAINT finance_requests_owner_fk FOREIGN KEY (company_id, owner_employee_id) REFERENCES employees (company_id, id),
  CONSTRAINT finance_requests_created_by_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id),
  CONSTRAINT finance_requests_id CHECK (id REGEXP '^[0-9a-f]{32}$'),
  CONSTRAINT finance_requests_kind CHECK (kind IN ('paymentRequest', 'reimbursement')),
  CONSTRAINT finance_requests_financial_post CHECK (financial_post IN ('GA', 'NPIP', 'TJB', 'DRONE')),
  CONSTRAINT finance_requests_category CHECK (CHAR_LENGTH(category) BETWEEN 1 AND 64 AND CHAR_LENGTH(category) = CHAR_LENGTH(TRIM(category)) AND LOWER(category) NOT IN ('gaji', 'payroll', 'salary')),
  CONSTRAINT finance_requests_description CHECK (CHAR_LENGTH(description) BETWEEN 1 AND 500 AND CHAR_LENGTH(description) = CHAR_LENGTH(TRIM(description))),
  CONSTRAINT finance_requests_amount CHECK (amount > 0 AND amount = FLOOR(amount)),
  CONSTRAINT finance_requests_payee_by_kind CHECK ((kind = 'paymentRequest' AND payee IS NOT NULL AND CHAR_LENGTH(payee) BETWEEN 1 AND 160 AND CHAR_LENGTH(payee) = CHAR_LENGTH(TRIM(payee))) OR (kind = 'reimbursement' AND payee IS NULL)),
  CONSTRAINT finance_requests_owner_by_kind CHECK ((kind = 'reimbursement' AND owner_employee_id IS NOT NULL) OR (kind = 'paymentRequest' AND owner_employee_id IS NULL)),
  CONSTRAINT finance_requests_document_date CHECK (document_date >= '1900-01-01'),
  CONSTRAINT finance_requests_status CHECK (status IN ('Draft', 'Submitted', 'Approved', 'Paid', 'Rejected', 'Cancelled')),
  CONSTRAINT finance_requests_status_reason CHECK ((status IN ('Rejected', 'Cancelled') AND status_reason IS NOT NULL AND CHAR_LENGTH(status_reason) BETWEEN 1 AND 200 AND CHAR_LENGTH(status_reason) = CHAR_LENGTH(TRIM(status_reason))) OR (status NOT IN ('Rejected', 'Cancelled') AND status_reason IS NULL)),
  CONSTRAINT finance_requests_version CHECK (version >= 1),
  CONSTRAINT finance_requests_idempotency_key_format CHECK (idempotency_key REGEXP '^[0-9a-f]{32}$'),
  CONSTRAINT finance_requests_created_by CHECK (created_by_user_id REGEXP '^[0-9a-f]{32}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
