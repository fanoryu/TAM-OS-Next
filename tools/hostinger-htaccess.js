#!/usr/bin/env node
/*
 * hostinger-htaccess.js — TAM OS (WP-2, backend deployment readiness)
 * -----------------------------------------------------------------
 * Renders the document-root `.htaccess` that applies the STATIC header contract of
 * tools/package-headers.js (the single source of truth) on the Hostinger web server, so the
 * host never carries a hand-edited copy of the headers. It is a renderer, not configuration:
 * nothing here touches a host, and the output holds no secret, path, hostname or credential.
 *
 *   node tools/hostinger-htaccess.js                 # staging: the static headers, no HSTS
 *   node tools/hostinger-htaccess.js --production    # adds HSTS (SDR-0002 §13.1) — production
 *                                                    # only, and only once Gate D authorizes it
 *   node tools/hostinger-htaccess.js --sha256 [--production]   # prints the output's SHA-256
 *
 * Output goes to stdout only; the operator saves it as `<document root>/.htaccess` (see
 * docs/BACKEND-DEPLOYMENT-RUNBOOK.md). Rules of the rendering, each checked by
 * tools/verify-build.js (WP-2):
 *   - /api/* is EXCLUDED: `SetEnvIf Request_URI "^/api(/|$)" TAMOS_API` and every Header line
 *     carries `env=!TAMOS_API`. The PHP API sets its own headers (server/src/Http/ApiHeaders.php,
 *     `Cache-Control: no-store, private`); a document-root rule must never replace them — a
 *     static `no-cache` on an API answer would let a CDN keep it (SDR-0002 §13.3).
 *   - `Header always set` replaces, never appends, so a header is sent once.
 *   - No <IfModule> wrapper: a host without mod_headers must FAIL (500), not serve the package
 *     silently without its Content-Security-Policy.
 *   - Directory listings off; index.html the directory index; explicit UTF-8 types for .js / .css
 *     (the package is served under `nosniff`), and the vendored LICENSE as text/plain.
 * Whether LiteSpeed on the account honours each directive is pre-deployment host evidence
 * (SDR-0002 E6), never assumed: the runbook's header probe proves it on the host.
 */
'use strict';
const crypto = require('crypto');
const { STATIC_HEADERS, HSTS_PRODUCTION } = require('./package-headers.js');

const API_ENV = 'TAMOS_API';
const API_MATCH = '^/api(/|$)';

// Apache/LiteSpeed double-quoted argument: only a literal backslash or double quote needs escaping.
function quote(value){
  if(/[\r\n]/.test(value)) throw new Error('header value with a line break');
  return '"' + String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

function renderDocumentRootHtaccess(opts){
  const production = !!(opts && opts.production);
  const lines = [
    '# TAM OS document root (' + (production ? 'PRODUCTION — only after Gate D' : 'staging') + ').',
    '# GENERATED by tools/hostinger-htaccess.js from tools/package-headers.js — do not edit on the host.',
    '# Static package files only: /api/* keeps the headers the PHP API sets itself.',
    'Options -Indexes',
    'DirectoryIndex index.html',
    'AddType "text/javascript; charset=utf-8" .js',
    'AddType "text/css; charset=utf-8" .css',
    'AddDefaultCharset utf-8',
    '<Files "LICENSE">',
    '  ForceType "text/plain; charset=utf-8"',
    '</Files>',
    'SetEnvIf Request_URI ' + quote(API_MATCH) + ' ' + API_ENV
  ];
  Object.keys(STATIC_HEADERS).forEach(function(name){
    lines.push('Header always set ' + name + ' ' + quote(STATIC_HEADERS[name]) + ' env=!' + API_ENV);
  });
  if(production) lines.push('Header always set Strict-Transport-Security ' + quote(HSTS_PRODUCTION) + ' env=!' + API_ENV);
  return lines.join('\n') + '\n';
}

// The headers a request path would receive from this file alone — a self-consistency model of
// the rendered directives (SetEnvIf + `env=!`), NOT evidence of host behaviour (SDR-0002 E6).
function modelHeaders(text, requestPath){
  const env = {};
  const out = {};
  text.split('\n').forEach(function(line){
    let m = /^SetEnvIf Request_URI "([^"]+)" ([A-Z_]+)$/.exec(line);
    if(m){ if(new RegExp(m[1]).test(requestPath)) env[m[2]] = true; return; }
    m = /^Header always set ([A-Za-z-]+) "((?:[^"\\]|\\.)*)" env=!([A-Z_]+)$/.exec(line);
    if(m && !env[m[3]]) out[m[1]] = m[2].replace(/\\(.)/g, '$1');
  });
  return out;
}

if(require.main === module){
  const args = process.argv.slice(2);
  const known = ['--production', '--sha256'];
  if(args.some(function(a){ return known.indexOf(a) === -1; })){
    process.stderr.write('usage: node tools/hostinger-htaccess.js [--production] [--sha256]\n');
    process.exit(2);
  }
  const text = renderDocumentRootHtaccess({ production: args.indexOf('--production') !== -1 });
  process.stdout.write(args.indexOf('--sha256') !== -1 ? crypto.createHash('sha256').update(text).digest('hex') + '\n' : text);
}

module.exports = { renderDocumentRootHtaccess, modelHeaders, API_ENV, API_MATCH };
